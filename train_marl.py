"""
MARL training with metaheuristic warm-start — the core experiment.

Shared-policy PPO over MultiRobotEnv (parameter sharing across robots),
optionally warm-started via Behavior Cloning (BC) on expert demonstrations
generated by generate_demos.py (BCO-GA or A* experts).

The paper's key figure comes from running this three times:
    python train_marl.py --tag cold                                  # no warm-start
    python train_marl.py --tag warm_astar --warmstart demos_astar.npz
    python train_marl.py --tag warm_bco   --warmstart demos_bco.npz
then overlaying runs/<tag>.csv learning curves (plot_curves.py).

Designed for Google Colab (GPU or CPU). Only needs:
    marl_env.py, this file, and the demos_*.npz files.
"""

import argparse
import csv
import os
import time

import numpy as np

try:
    import torch
    import torch.nn as nn
except ImportError:
    raise SystemExit(
        "PyTorch is required. On Colab it's preinstalled; locally run:\n"
        "  py -3.10 -m pip install torch --index-url https://download.pytorch.org/whl/cpu"
    )

from marl_env import MultiRobotEnv, OBS_DIM, N_ACTIONS

DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")


# ─────────────────────────────────────────
# Shared policy network (actor-critic MLP)
# ─────────────────────────────────────────
class PolicyNet(nn.Module):
    def __init__(self, hidden: int = 192):
        super().__init__()
        self.trunk = nn.Sequential(
            nn.Linear(OBS_DIM, hidden), nn.Tanh(),
            nn.Linear(hidden, hidden), nn.Tanh(),
        )
        self.pi = nn.Linear(hidden, N_ACTIONS)
        self.v = nn.Linear(hidden, 1)

    def forward(self, x):
        h = self.trunk(x)
        return self.pi(h), self.v(h).squeeze(-1)

    @torch.no_grad()
    def act(self, obs_np: np.ndarray, greedy: bool = False):
        x = torch.as_tensor(obs_np, dtype=torch.float32, device=DEVICE)
        logits, value = self.forward(x)
        dist = torch.distributions.Categorical(logits=logits)
        action = torch.argmax(logits, dim=-1) if greedy else dist.sample()
        return (action.cpu().numpy(),
                dist.log_prob(action).cpu().numpy(),
                value.cpu().numpy())


# ─────────────────────────────────────────
# Behavior Cloning warm-start
# ─────────────────────────────────────────
def behavior_cloning(net: PolicyNet, demo_path: str,
                     epochs: int = 15, batch: int = 256, lr: float = 1e-3,
                     demo_cap: int = 0, cap_seed: int = 0):
    data = np.load(demo_path)
    obs_np, act_np = data["obs"], data["actions"]
    n_full = len(act_np)

    # Equal-demonstration-budget control. A population planner yields many more
    # (obs, action) pairs than a deterministic one simply by rolling K variants
    # per scenario, so an uncapped comparison confounds DIVERSITY with DATA
    # VOLUME. Capping both arms to the same number of pairs isolates diversity.
    # The subsample is drawn with the run's own seed, so averaging over seeds
    # also averages over subsample draws.
    if demo_cap and demo_cap < n_full:
        rng = np.random.default_rng(cap_seed)
        sel = rng.choice(n_full, size=demo_cap, replace=False)
        obs_np, act_np = obs_np[sel], act_np[sel]

    obs = torch.as_tensor(obs_np, dtype=torch.float32, device=DEVICE)
    act = torch.as_tensor(act_np, dtype=torch.long, device=DEVICE)
    n = len(act)
    uniq = len(np.unique(np.round(obs_np.astype(np.float64) / 0.05), axis=0))
    cap_note = f" (capped from {n_full})" if n < n_full else ""
    print(f"[BC] warm-start from {demo_path}: {n} samples{cap_note} "
          f"(expert = {data['planner']})")
    print(f"[BC] unique states @0.05 quantization: {uniq} "
          f"(coverage ratio {uniq/n:.3f})")

    opt = torch.optim.Adam(net.parameters(), lr=lr)
    ce = nn.CrossEntropyLoss()
    for ep in range(epochs):
        perm = torch.randperm(n, device=DEVICE)
        tot, correct = 0.0, 0
        for s in range(0, n, batch):
            idx = perm[s:s + batch]
            logits, _v = net(obs[idx])
            loss = ce(logits, act[idx])
            opt.zero_grad()
            loss.backward()
            opt.step()
            tot += float(loss) * len(idx)
            correct += int((logits.argmax(-1) == act[idx]).sum())
        if ep == 0 or (ep + 1) % 5 == 0:
            print(f"[BC] epoch {ep+1:2d}/{epochs} | loss {tot/n:.4f} "
                  f"| acc {correct/n*100:.1f}%")
    print("[BC] done.\n")


# ─────────────────────────────────────────
# Rollout buffer (per-robot trajectories, shared policy)
# ─────────────────────────────────────────
class Buffer:
    def __init__(self, num_robots: int):
        self.n = num_robots
        self.reset()

    def reset(self):
        self.obs = [[] for _ in range(self.n)]
        self.act = [[] for _ in range(self.n)]
        self.logp = [[] for _ in range(self.n)]
        self.val = [[] for _ in range(self.n)]
        self.rew = [[] for _ in range(self.n)]
        self.done = [[] for _ in range(self.n)]

    def add(self, i, o, a, lp, v, r, d):
        self.obs[i].append(o)
        self.act[i].append(a)
        self.logp[i].append(lp)
        self.val[i].append(v)
        self.rew[i].append(r)
        self.done[i].append(d)

    def compute_gae(self, gamma=0.99, lam=0.95):
        all_obs, all_act, all_logp, all_adv, all_ret = [], [], [], [], []
        for i in range(self.n):
            if not self.obs[i]:
                continue
            rew = np.array(self.rew[i], dtype=np.float32)
            val = np.array(self.val[i], dtype=np.float32)
            done = np.array(self.done[i], dtype=np.float32)
            T = len(rew)
            adv = np.zeros(T, dtype=np.float32)
            last = 0.0
            for t in reversed(range(T)):
                next_v = 0.0 if t == T - 1 or done[t] else val[t + 1]
                delta = rew[t] + gamma * next_v * (1 - done[t]) - val[t]
                last = delta + gamma * lam * (1 - done[t]) * last
                adv[t] = last
            ret = adv + val
            all_obs.append(np.array(self.obs[i], dtype=np.float32))
            all_act.append(np.array(self.act[i], dtype=np.int64))
            all_logp.append(np.array(self.logp[i], dtype=np.float32))
            all_adv.append(adv)
            all_ret.append(ret)
        return (np.concatenate(all_obs), np.concatenate(all_act),
                np.concatenate(all_logp), np.concatenate(all_adv),
                np.concatenate(all_ret))


# ─────────────────────────────────────────
# Evaluation (greedy policy)
# ─────────────────────────────────────────
def evaluate(net: PolicyNet, episodes: int = 5, seed0: int = 9000):
    env = MultiRobotEnv(num_robots=5, num_moving=3, num_static=3)
    succ, reached = 0, 0
    for e in range(episodes):
        obs = env.reset(seed=seed0 + e)
        done, info = False, {}
        while not done:
            actions, _lp, _v = net.act(obs, greedy=True)
            obs, _r, done, info = env.step(actions)
        succ += int(info["success"])
        reached += info["reached"]
    return succ / episodes, reached / (episodes * env.num_robots)


# ─────────────────────────────────────────
# PPO training loop
# ─────────────────────────────────────────
def train(tag: str, warmstart: str, total_steps: int, seed: int,
          rollout_len: int = 512, epochs: int = 4, batch: int = 256,
          lr: float = 3e-4, clip: float = 0.2,
          vf_coef: float = 0.5, ent_coef: float = 0.01,
          bc_aux: float = 0.0, demo_cap: int = 0, out_dir: str = "runs"):
    torch.manual_seed(seed)
    np.random.seed(seed)

    net = PolicyNet().to(DEVICE)
    demo_obs = demo_act = None
    if warmstart and warmstart != "none":
        behavior_cloning(net, warmstart, demo_cap=demo_cap, cap_seed=seed)
        if bc_aux > 0.0:
            # keep demonstrations in the loop: an auxiliary BC term is added to
            # every PPO update, so the demonstration SOURCE keeps influencing
            # training rather than only its initialization.
            d = np.load(warmstart)
            demo_obs = torch.as_tensor(d["obs"], dtype=torch.float32, device=DEVICE)
            demo_act = torch.as_tensor(d["actions"], dtype=torch.long, device=DEVICE)
            print(f"[aux-BC] keeping {len(demo_act)} demos in the loop "
                  f"(coef {bc_aux})")

    opt = torch.optim.Adam(net.parameters(), lr=lr)
    ce = nn.CrossEntropyLoss()
    env = MultiRobotEnv(num_robots=5, num_moving=3, num_static=3)

    os.makedirs(out_dir, exist_ok=True)
    log_path = os.path.join(out_dir, f"{tag}.csv")
    log_f = open(log_path, "w", newline="")
    logger = csv.writer(log_f)
    logger.writerow(["steps", "mean_ep_return", "eval_success",
                     "eval_reached", "seconds"])

    ep_seed = seed * 100000
    obs = env.reset(seed=ep_seed)
    ep_return = 0.0
    ep_returns = []
    steps_done = 0
    t_start = time.time()
    buf = Buffer(env.num_robots)

    print(f"=== training '{tag}' | warmstart={warmstart or 'none'} "
          f"| device={DEVICE} | total={total_steps} env-steps ===")

    while steps_done < total_steps:
        buf.reset()
        for _ in range(rollout_len):
            actions, logps, values = net.act(obs)
            active = ~env.reached
            next_obs, rewards, done, info = env.step(actions)
            steps_done += 1
            ep_return += float(rewards.sum())

            for i in range(env.num_robots):
                if not active[i]:
                    continue
                agent_done = done or env.reached[i]
                buf.add(i, obs[i], actions[i], logps[i], values[i],
                        rewards[i], float(agent_done))
            obs = next_obs

            if done:
                ep_returns.append(ep_return)
                ep_return = 0.0
                ep_seed += 1
                obs = env.reset(seed=ep_seed)

        # PPO update
        b_obs, b_act, b_logp, b_adv, b_ret = buf.compute_gae()
        b_adv = (b_adv - b_adv.mean()) / (b_adv.std() + 1e-8)
        t_obs = torch.as_tensor(b_obs, device=DEVICE)
        t_act = torch.as_tensor(b_act, device=DEVICE)
        t_logp = torch.as_tensor(b_logp, device=DEVICE)
        t_adv = torch.as_tensor(b_adv, device=DEVICE)
        t_ret = torch.as_tensor(b_ret, device=DEVICE)

        n = len(t_act)
        for _ep in range(epochs):
            perm = torch.randperm(n, device=DEVICE)
            for s in range(0, n, batch):
                idx = perm[s:s + batch]
                logits, value = net(t_obs[idx])
                dist = torch.distributions.Categorical(logits=logits)
                logp = dist.log_prob(t_act[idx])
                ratio = torch.exp(logp - t_logp[idx])
                surr1 = ratio * t_adv[idx]
                surr2 = torch.clamp(ratio, 1 - clip, 1 + clip) * t_adv[idx]
                pi_loss = -torch.min(surr1, surr2).mean()
                v_loss = ((value - t_ret[idx]) ** 2).mean()
                ent = dist.entropy().mean()
                loss = pi_loss + vf_coef * v_loss - ent_coef * ent

                # auxiliary behavior-cloning term (demos kept in the loop)
                if demo_act is not None:
                    di = torch.randint(0, len(demo_act), (batch,), device=DEVICE)
                    dlogits, _ = net(demo_obs[di])
                    loss = loss + bc_aux * ce(dlogits, demo_act[di])

                opt.zero_grad()
                loss.backward()
                nn.utils.clip_grad_norm_(net.parameters(), 0.5)
                opt.step()

        # Log
        mean_ret = float(np.mean(ep_returns[-10:])) if ep_returns else 0.0
        ev_succ, ev_reached = evaluate(net, episodes=5)
        secs = time.time() - t_start
        logger.writerow([steps_done, f"{mean_ret:.2f}",
                         f"{ev_succ:.2f}", f"{ev_reached:.2f}", f"{secs:.0f}"])
        # A transient filesystem error must not destroy a 45-minute run.
        # Google Drive's virtual filesystem intermittently fails a flush on a
        # long-lived handle with OSError 22, which previously killed a run
        # outright. Retry, and if the handle is genuinely dead, reopen it in
        # append mode and carry on.
        for attempt in range(4):
            try:
                log_f.flush()
                break
            except OSError as e:
                if attempt == 3:
                    print(f"[warn] log flush failed ({e}); continuing without it")
                    break
                time.sleep(1.0 * (attempt + 1))
                try:
                    log_f.close()
                except OSError:
                    pass
                try:
                    log_f = open(log_path, "a", newline="")
                    logger = csv.writer(log_f)
                except OSError:
                    pass
        print(f"steps {steps_done:>8d} | ep_ret(10) {mean_ret:>8.1f} "
              f"| eval succ {ev_succ*100:>4.0f}% | reached {ev_reached*100:>4.0f}% "
              f"| {secs:>5.0f}s")

    # The model file is written only here, so its presence is the marker that
    # a run finished; resume logic relies on that.
    torch.save(net.state_dict(), os.path.join(out_dir, f"{tag}.pt"))
    try:
        log_f.close()
    except OSError:
        pass
    print(f"\nSaved model -> {out_dir}/{tag}.pt , log -> {log_path}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", required=True, help="run name (csv/model file)")
    ap.add_argument("--warmstart", default="none",
                    help="demos .npz for BC warm-start, or 'none'")
    ap.add_argument("--total-steps", type=int, default=200_000)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--bc-aux", type=float, default=0.0,
                    help="auxiliary BC coefficient to keep demos in the loop "
                         "(0 = warm-start only)")
    ap.add_argument("--demo-cap", type=int, default=0,
                    help="subsample the demonstration set to this many (obs, "
                         "action) pairs before BC (0 = use all). Use it to "
                         "equalize the demonstration budget across experts so "
                         "diversity is not confounded with data volume.")
    ap.add_argument("--out-dir", default="runs",
                    help="where to write <tag>.csv and <tag>.pt. Point this at "
                         "a local disk when the project lives on a synced "
                         "drive (Google Drive, OneDrive): their virtual "
                         "filesystems fail long-lived write handles.")
    args = ap.parse_args()
    train(args.tag, args.warmstart, args.total_steps, args.seed,
          bc_aux=args.bc_aux, demo_cap=args.demo_cap, out_dir=args.out_dir)
